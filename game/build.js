'use strict';
/*
 * 打包脚本：把引擎（CommonJS 模块）、模型参数、Worker 与界面代码内联为单个 HTML 文件。
 *   node game/build.js   →   game/dist/amazons.html
 * 生成的文件双击即可在浏览器中打开（file:// 协议），无需服务器与网络。
 */
const fs = require('fs');
const path = require('path');
const root = path.join(__dirname, '..');
const rd = p => fs.readFileSync(path.join(root, p), 'utf8');

const files = ['core.js', 'eval.js', 'movegen.js', 'search.js', 'mcts.js', 'policy.js', 'agents.js', 'index.js'];
let engine = '/* AmazonsAI engine bundle — generated by game/build.js */\n(function (global) {\n"use strict";\nconst __mods = {};\nconst __cache = {};\n' +
  'function require(name) { const k = name.replace(/^\\.\\//, "").replace(/^\\.\\.\\/engine\\//, ""); if (__cache[k]) return __cache[k].exports; const m = { exports: {} }; __cache[k] = m; __mods[k](m, m.exports, require); return m.exports; }\n';
for (const f of files) engine += `__mods[${JSON.stringify(f)}] = function (module, exports, require) {\n${rd('engine/' + f)}\n};\n`;
engine += 'global.AmazonsAI = require("index.js");\n})(typeof self !== "undefined" ? self : this);\n';

const readJSON = p => fs.existsSync(path.join(root, p)) ? JSON.parse(rd(p)) : null;
const pw = readJSON('models/policy_weights.json'), tw = readJSON('models/eval_weights_tuned.json'), ui = readJSON('models/ui_config.json');
let models = '';
models += `var POLICY_THETA = ${pw ? JSON.stringify(pw.theta) : 'null'};\n`;
models += `var TUNED_WEIGHTS = ${tw ? JSON.stringify(tw.weights) : 'null'};\n`;
models += `var WIN_K = ${tw && (tw.K_hand || tw.K) ? (tw.K_hand || tw.K) : "null"};\n`;
models += `var AI_LIST_CFG = ${ui ? JSON.stringify(ui.ai_list) : 'undefined'};\n`;
const op = JSON.parse(rd('data/openings.json')).openings.map(o => o.moves);
models += `var OPENINGS = ${JSON.stringify(op)};\n`;

const worker = engine + '\n' + models + '\n' + rd('game/src/worker.js');
let html = rd('game/src/index.html');
const put = (tag, s) => { if (!html.includes(tag)) throw new Error(tag); html = html.split(tag).join(s.replace(/<\/script/gi, '<\\/script')); };
put('/*STYLE*/', rd('game/src/style.css'));
put('/*ENGINE*/', engine);
put('/*MODELS*/', models);
put('/*WORKER*/', worker);
put('/*APP*/', rd('game/src/app.js'));
fs.mkdirSync(path.join(__dirname, 'dist'), { recursive: true });
fs.writeFileSync(path.join(__dirname, 'dist/amazons.html'), html);
fs.writeFileSync(path.join(__dirname, 'dist/amazons-engine.js'), engine);
console.log('built game/dist/amazons.html', (html.length / 1024).toFixed(1) + ' KB');
